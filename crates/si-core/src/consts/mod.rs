/// A row's published sweep value, if a `*_sweep.json` has replaced its
/// placeholder (11 §4 DoD 2). The table is generated by the harness and committed;
/// a hand edit is caught by `check_registry_size`.
pub fn swept_value(row: &ConstRow) -> Option<&'static SweptValue> {
    swept::value(row.name)
}

/// engineering/12 §3.3 / 13 §3.4: the v2 arc added 22 rows and the tongue 8 more,
/// so hash item 8 changes for every run. The bump is the announcement, not a side
/// effect, and it moves with the three `EMPTY_STATE_MD5_SEED_ZERO` goldens.
pub const CONSTS_VERSION: u16 = 0x0003;
pub const PLACEHOLDER_TAG: &str = "UNMEASURED_PLACEHOLDER";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Class {
    Law,
    Species,
    Temperament,
    Ruling,
    Derived,
    /// **OD-175** / 13 §3.5: the sixth class. A `Tongue` row is drawn like a
    /// temperament row and refused like a law row, and it is inert by
    /// construction — `sweep: None` keeps it out of the placeholder, swept and
    /// axis buckets, and `launch_constants`' `Species | Ruling` guard refuses it
    /// without one character of edit.
    Tongue,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Unit {
    Rounds,
    Q12,
    U8,
    Hundredths,
    Fraction,
    Count,
    Index,
    Bool,
    Ticks,
    Shape,
}

#[derive(Clone, Copy, Debug)]
pub struct ConstRow {
    pub name: &'static str,
    pub home: &'static str,
    pub gate: &'static str,
    pub class: Class,
    pub unit: Unit,
    pub lo: i64,
    pub hi: i64,
    pub grid: i64,
    pub sweep: Option<&'static str>,
    pub law_value: Option<i64>,
    /// engineering/12 §3.1: a swept SPECIES row whose shipped default the design
    /// declares rather than sweeps (`IGN_WEIGHT_SILT = 0`). It is not a
    /// placeholder — no midpoint is invented — and not a LAW value.
    pub declared: Option<i64>,
    /// False for a family, a rule set or a list; those have no single scalar.
    pub scalar: bool,
}

