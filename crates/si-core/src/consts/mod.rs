//! 03 — the constants registry, one row per tunable, with home, gate, grid and
//! legal range. OD-86's placeholder policy applies to scalar SPECIES rows whose
//! value a sweep owns: `lo + round_half_up((hi − lo)/2)` snapped to the row's
//! grid, tagged `UNMEASURED_PLACEHOLDER`, replaced only by a `*_sweep.json`.
//!
//! A TEMPERAMENT row has no placeholder: its value is `(birth_seed, position in
//! DERIV_ORDER)`, drawn at wake (10 §4). A non-scalar row (a curve family, a
//! rule set, a tier list) has no placeholder either; its artifact supplies it.

